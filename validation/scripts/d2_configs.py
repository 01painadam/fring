"""D2: write the fring-run configs of the arc error test (role A6).

Usage:
    uv run python scripts/d2_configs.py            # 5-year set -> reference/d2/configs/
    uv run python scripts/d2_configs.py --t0       # zero-step check set -> reference/d2/configs_t0/

Sets (per core: "ecc" with e = 0.00235 and the apse of params/ring.toml, "circ" with e = 0):
    ring: 2 seeds.  arc: widths 5, 10, 30 deg x centres 0, 90, 180, 270 deg (4 seeds).
All runs: GPU, no collisions, Prometheus and Pandora, N = 1e5, h = 31,557,600 / 88,582 s.
"""
from __future__ import annotations

import argparse
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "validation" / "reference" / "d2"

STEP_S = 31_557_600.0 / 88_582.0  # 356.2537 s, 150 steps per orbit
WIDTHS_DEG = (5.0, 10.0, 30.0)
CENTRES_DEG = (0.0, 90.0, 180.0, 270.0)
RING_SEEDS = (20261301, 20261302)
SIGMA_A_KM = 10.0  # D2 choice: between the observed core (<= 1 km) and the dust strands (10 to 30 km)
N_PARTICLES = 100_000
FRAME_EVERY = 22_145  # 0.25 yr


def ring_params() -> dict:
    with open(REPO / "params" / "ring.toml", "rb") as f:
        return tomllib.load(f)["core"]


def run_name(core: str, domain: str, width: float | None, centre: float | None, seed_idx: int) -> str:
    if domain == "ring":
        return f"d2-{core}-ring-s{seed_idx}"
    return f"d2-{core}-arc{int(width):02d}-c{int(centre):03d}"


def config_text(core: str, domain: str, width, centre, seed: int, name: str, years: float,
                frame_every: int) -> str:
    rp = ring_params()
    a0 = rp["semi_major_axis_km"]
    ecc = rp["eccentricity"] if core == "ecc" else 0.0
    apse = rp["apse_longitude_deg"]
    dom = '[domain]\nkind = "full_ring"\n' if domain == "ring" else (
        f'[domain]\nkind = "arc"\nwidth_deg = {width}\ncentre_longitude_deg = {centre}\n')
    return f"""# D2 (A6), generated by validation/scripts/d2_configs.py. Do not edit.
[run]
name = "{name}"
backend = "gpu"
seed = {seed}
params_dir = "params"

[time]
step_s = {STEP_S!r}
duration_years = {years!r}

[frame]
reference_semi_major_axis_km = {a0}

{dom}
[moons]
include = ["prometheus", "pandora"]

[particles]
count = {N_PARTICLES}

[particles.distribution]
kind = "core"
semi_major_axis_km = {a0}
sigma_semi_major_axis_km = {SIGMA_A_KM}
eccentricity = {ecc}
apse_longitude_deg = {apse}

[collisions]
model = "none"

[output]
frame_every_steps = {frame_every}
stats_every_steps = {frame_every}
velocities = true
"""


def all_runs(t0: bool):
    """Yield (name, domain, width, centre, seed, core)."""
    seed = 20261310
    for core in ("ecc", "circ"):
        base = 0 if core == "ecc" else 100
        for i, s in enumerate(RING_SEEDS):
            yield run_name(core, "ring", None, None, i), "ring", None, None, s + base, core
        for w in WIDTHS_DEG:
            for c in CENTRES_DEG:
                seed += 1
                yield run_name(core, "arc", w, c, 0), "arc", w, c, seed + base, core


def write_cpu_set() -> None:
    """CPU cross-check (needs RUN-MODELS): ring seed 0 and the 10 deg arc centre 0, both cores, N = 2e4."""
    d = OUT / "configs_cpu"
    d.mkdir(parents=True, exist_ok=True)
    names = []
    for name, dom, w, c, seed, core in all_runs(False):
        if not ((dom == "ring" and name.endswith("s0")) or (w == 10.0 and c == 0.0)):
            continue
        cpu_name = name.replace("d2-", "d2cpu-", 1)
        text = config_text(core, dom, w, c, seed, cpu_name, 5.0, FRAME_EVERY)
        text = text.replace('backend = "gpu"', 'backend = "cpu"').replace(f"count = {N_PARTICLES}", "count = 20000")
        (d / f"{cpu_name}.toml").write_text(text)
        names.append(cpu_name)
    (d / "list.txt").write_text("\n".join(names) + "\n")
    print(f"{len(names)} configs in {d}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--t0", action="store_true", help="zero-step check set (2 steps, frame every step)")
    ap.add_argument("--cpu", action="store_true", help="CPU cross-check set: N = 2e4, ring and 10 deg arc (centre 0)")
    args = ap.parse_args()
    if args.cpu:
        return write_cpu_set()
    sub = "configs_t0" if args.t0 else "configs"
    years = 2.0 * STEP_S / 31_557_600.0 * 0.99 if args.t0 else 5.0
    fe = 1 if args.t0 else FRAME_EVERY
    d = OUT / sub
    d.mkdir(parents=True, exist_ok=True)
    names = []
    for name, dom, w, c, seed, core in all_runs(args.t0):
        if args.t0 and not (dom == "ring" and name.endswith("s0") or c == 0.0):
            continue
        (d / f"{name}.toml").write_text(config_text(core, dom, w, c, seed, name, years, fe))
        names.append(name)
    (d / "list.txt").write_text("\n".join(names) + "\n")
    print(f"{len(names)} configs in {d}")


if __name__ == "__main__":
    main()
