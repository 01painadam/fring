//! Builds the system and the initial particles from a config file, the same
//! way as `fring-run` does (`apps/fring-run/src/lib.rs`), so that an analysis
//! harness sees the same initial conditions as a production run.

use fring_model::params::{moons_from_toml_str, saturn_from_toml_str};
use fring_model::physics::{
    DEFAULT_INTERVAL_S, MoonInit, SaturnField, build_ephemeris, generate_particles,
};
use fring_model::{Error, InitialState, Result, RunConfig, SaturnParams, System};
use std::path::Path;

/// Everything that a backend needs.
pub struct Setup {
    /// The run config.
    pub config: RunConfig,
    /// Saturn and the moon ephemeris.
    pub system: System,
    /// Particles at t = 0.
    pub init: InitialState,
    /// Saturn's parameters.
    pub saturn: SaturnParams,
    /// Saturn's field.
    pub field: SaturnField<f64>,
}

fn read(path: &Path) -> Result<String> {
    std::fs::read_to_string(path).map_err(|e| Error::Io(format!("{}: {e}", path.display())))
}

/// Loads `params/saturn.toml` and `params/moons.toml` from `params_dir`.
pub fn load_params(params_dir: &Path) -> Result<(SaturnParams, Vec<MoonInit>)> {
    let saturn = saturn_from_toml_str(&read(&params_dir.join("saturn.toml"))?)?;
    let moons = moons_from_toml_str(&read(&params_dir.join("moons.toml"))?)?;
    Ok((saturn, moons))
}

/// Loads the moons from one file with the layout of `params/moons.toml`, for
/// example the variant `params/variants/gr03b-moons.toml` (task A4-ANALYSIS).
pub fn load_moons_file(path: &Path) -> Result<Vec<MoonInit>> {
    moons_from_toml_str(&read(path)?)
}

/// Makes the setup for the config file at `config_path`.
pub fn load(config_path: &Path) -> Result<Setup> {
    let config = RunConfig::from_toml_str(&read(config_path)?)?;
    config.validate()?;
    let (saturn, all) = load_params(Path::new(&config.run.params_dir))?;
    let mut moons = Vec::new();
    for name in &config.moons.include {
        let m = all
            .iter()
            .find(|m| &m.name == name)
            .ok_or_else(|| Error::Config(format!("unknown moon {name:?}")))?;
        moons.push(m.clone());
    }
    let n_steps = config.time.n_steps();
    let step_s = config.time.step_s;
    let eph = build_ephemeris(
        &saturn,
        &moons,
        n_steps as f64 * step_s + DEFAULT_INTERVAL_S,
        DEFAULT_INTERVAL_S,
    )?;
    let field = SaturnField::<f64>::from_params(&saturn);
    let particles = generate_particles(
        &field,
        &config.particles.distribution,
        config.particles.count,
        config.run.seed,
    )?;
    Ok(Setup {
        init: InitialState {
            time_s: 0.0,
            particles,
        },
        system: System { saturn, moons: eph },
        saturn,
        field,
        config,
    })
}

/// The number after `key =` on its own line in the text of a TOML file (the
/// first match; keys that only start with `key` do not match).
pub fn toml_number(text: &str, key: &str) -> Option<f64> {
    text.lines().find_map(|l| {
        let (k, v) = l.split_once('=')?;
        if k.trim() == key {
            v.split('#').next()?.trim().parse().ok()
        } else {
            None
        }
    })
}

/// One config of the A2-ANALYSIS map of eccentric orbits: an `eccentric_band`
/// over `[lo_km, hi_km)` with `count` particles. With `eccentricity = 0` it is
/// the circular control (same Philox draws, so the same a and longitude for
/// each id). The moons, the step and the indicator are those of
/// `chaos-map-main10.toml` (ADR 0008), and `renorm_steps` scales with the step.
#[allow(clippy::too_many_arguments)]
pub fn ecc_config(
    name: &str,
    seed: u64,
    step_s: f64,
    renorm_steps: u32,
    years: f64,
    (lo_km, hi_km): (f64, f64),
    count: u32,
    eccentricity: f64,
    apse_longitude_deg: f64,
) -> String {
    format!(
        "# A2-ANALYSIS (generated by `fring-analyse ecc-configs`). e = 0 is the circular control.\n\
[run]\nname = \"{name}\"\nbackend = \"gpu\"\nseed = {seed}\nparams_dir = \"params\"\n\n\
[time]\nstep_s = {step_s}\nduration_years = {years}\n\n\
[frame]\nreference_semi_major_axis_km = 140222.43\n\n\
[domain]\nkind = \"full_ring\"\n\n\
[moons]\ninclude = [\"prometheus\", \"pandora\"]\n\n\
[particles]\ncount = {count}\n\n\
[particles.distribution]\nkind = \"eccentric_band\"\nmin_semi_major_axis_km = {lo_km:.1}\nmax_semi_major_axis_km = {hi_km:.1}\neccentricity = {eccentricity}\napse_longitude_deg = {apse_longitude_deg}\n\n\
[collisions]\nmodel = \"none\"\n\n\
[output]\nframe_every_steps = 100000000\nstats_every_steps = 100000000\nvelocities = false\n\n\
[diagnostics.chaos]\nmethod = \"shadow\"\noffset_km = 1.0\nrenorm_steps = {renorm_steps}\n"
    )
}

/// One run of the eccentric map: name, seed, bin, e, apse longitude (deg), step (s), renorm steps.
#[derive(Debug, Clone, PartialEq)]
pub struct EccJob {
    pub name: String,
    pub seed: u64,
    pub bin: usize,
    pub ecc: f64,
    pub apse_deg: f64,
    pub step_s: f64,
    pub renorm_steps: u32,
}

/// Step of the A2-ANALYSIS map (150 steps per orbit), seconds.
pub const ECC_STEP_S: f64 = 356.2537;

/// The jobs of `fring-analyse ecc-configs`. `set` is `std` (every bin as ecc and
/// circular control; for `years <= 10` also the apse + 120 deg and seed-repeat
/// runs of bins 0, 2 and 21), `ecc` (only the ecc run of each bin in `bins`) or
/// `phase120` (only the apse + 120 deg run of each bin in `bins`). `step_div`
/// divides the step and multiplies the renorm interval, so the renorm time stays
/// the same (A5-ANALYSIS uses 4). The seed is 20261200 + bin in every set, so
/// the initial conditions match the `std` runs bin by bin.
pub fn ecc_jobs(
    years: f64,
    tag: &str,
    step_div: u32,
    bins: &[usize],
    set: &str,
    ecc: f64,
    apse_deg: f64,
) -> std::result::Result<Vec<EccJob>, String> {
    let (step_s, renorm_steps) = (ECC_STEP_S / f64::from(step_div), 100 * step_div);
    let job = |name: String, seed: u64, bin: usize, ecc: f64, apse_deg: f64| EccJob {
        name,
        seed,
        bin,
        ecc,
        apse_deg,
        step_s,
        renorm_steps,
    };
    let phase = (apse_deg + 120.0) % 360.0;
    let mut v = Vec::new();
    match set {
        "std" => {
            for bin in 0..22usize {
                let seed = 20_261_200 + bin as u64;
                v.push(job(
                    format!("{tag}-ecc-b{bin:02}"),
                    seed,
                    bin,
                    ecc,
                    apse_deg,
                ));
                v.push(job(
                    format!("{tag}-circ-b{bin:02}"),
                    seed,
                    bin,
                    0.0,
                    apse_deg,
                ));
            }
            if years <= 10.0 {
                for bin in [0usize, 2, 21] {
                    let seed = 20_261_200 + bin as u64;
                    v.push(job(
                        format!("{tag}-ecc-phase120-b{bin:02}"),
                        seed,
                        bin,
                        ecc,
                        phase,
                    ));
                    v.push(job(
                        format!("{tag}-ecc-repeat-b{bin:02}"),
                        seed + 1000,
                        bin,
                        ecc,
                        apse_deg,
                    ));
                }
            }
        }
        "ecc" | "phase120" => {
            for &bin in bins {
                if bin >= 22 {
                    return Err(format!("bin {bin} is not in 0..22"));
                }
                let seed = 20_261_200 + bin as u64;
                if set == "ecc" {
                    v.push(job(
                        format!("{tag}-ecc-b{bin:02}"),
                        seed,
                        bin,
                        ecc,
                        apse_deg,
                    ));
                } else {
                    v.push(job(
                        format!("{tag}-ecc-phase120-b{bin:02}"),
                        seed,
                        bin,
                        ecc,
                        phase,
                    ));
                }
            }
        }
        other => return Err(format!("unknown set {other} (std|ecc|phase120)")),
    }
    Ok(v)
}

#[cfg(test)]
mod tests {
    use super::*;
    use fring_model::config::Distribution;

    #[test]
    fn ring_values_and_generated_config() {
        let ring = include_str!("../../../params/ring.toml");
        let e = toml_number(ring, "eccentricity").unwrap();
        let w = toml_number(ring, "apse_longitude_deg").unwrap();
        assert_eq!((e, w), (0.00235, 353.78));
        let text = ecc_config(
            "t",
            5,
            356.2537,
            100,
            10.0,
            (140_150.0, 140_175.0),
            5000,
            e,
            w,
        );
        let cfg = RunConfig::from_toml_str(&text).unwrap();
        cfg.validate().unwrap();
        assert_eq!(cfg.particles.count, 5000);
        match cfg.particles.distribution {
            Distribution::EccentricBand {
                eccentricity,
                apse_longitude_deg,
                ..
            } => {
                assert_eq!((eccentricity, apse_longitude_deg), (e, w));
            }
            d => panic!("{d:?}"),
        }
    }

    #[test]
    fn ecc_jobs_sets() {
        let (e, w) = (0.00235, 353.78);
        let std10 = ecc_jobs(10.0, "t", 1, &[], "std", e, w).unwrap();
        assert_eq!(std10.len(), 50);
        assert!(
            std10
                .iter()
                .all(|j| j.step_s == ECC_STEP_S && j.renorm_steps == 100)
        );
        let std30 = ecc_jobs(30.0, "t", 1, &[], "std", e, w).unwrap();
        assert_eq!(std30.len(), 44);
        let h4 = ecc_jobs(10.0, "x", 4, &[0, 21], "ecc", e, w).unwrap();
        assert_eq!(h4.len(), 2);
        assert_eq!(
            (h4[1].name.as_str(), h4[1].seed, h4[1].renorm_steps),
            ("x-ecc-b21", 20_261_221, 400)
        );
        assert!((h4[0].step_s * 4.0 - ECC_STEP_S).abs() < 1e-12);
        // Same seed, e and apse as the std run of the same bin.
        let base = std10.iter().find(|j| j.name == "t-ecc-b21").unwrap();
        assert_eq!(
            (base.seed, base.ecc, base.apse_deg),
            (h4[1].seed, h4[1].ecc, h4[1].apse_deg)
        );
        let p = ecc_jobs(30.0, "p", 1, &(0..22).collect::<Vec<_>>(), "phase120", e, w).unwrap();
        assert_eq!(p.len(), 22);
        assert!((p[0].apse_deg - 113.78).abs() < 1e-9 && p[5].name == "p-ecc-phase120-b05");
        assert!(ecc_jobs(10.0, "x", 1, &[22], "ecc", e, w).is_err());
        assert!(ecc_jobs(10.0, "x", 1, &[], "bogus", e, w).is_err());
    }

    /// The GR03b variant file loads, with the GR03b masses and the nominal states.
    #[test]
    fn gr03b_variant_has_gr03b_masses_and_nominal_states() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../params");
        let nominal = load_moons_file(&root.join("moons.toml")).unwrap();
        let variant = load_moons_file(&root.join("variants/gr03b-moons.toml")).unwrap();
        let gm = |m: &[MoonInit], n: &str| m.iter().find(|x| x.name == n).unwrap().gm_km3_s2;
        assert_eq!(gm(&variant, "prometheus"), 0.02200);
        assert_eq!(gm(&variant, "pandora"), 0.01301);
        assert_eq!(gm(&nominal, "prometheus"), 0.01071);
        for (a, b) in nominal.iter().zip(&variant) {
            assert_eq!(a.name, b.name);
            assert_eq!(a.state.position_km, b.state.position_km);
            assert_eq!(a.state.velocity_km_s, b.state.velocity_km_s);
        }
    }
}
